    def test_docker_actions_require_complete_literal_content_digests(self):
        references = [
            "docker://alpine:3", "docker://alpine", "docker://",
            "Docker://alpine:3", "DoCkEr://alpine:latest",
            f"docker://@{DOCKER_DIGEST}",
            "docker://alpine@sha256:",
            "docker://alpine@sha256:" + "a" * 63,
            "docker://alpine@sha256:" + "a" * 65,
            "docker://alpine@sha256:" + "A" * 64,
            "DOCKER://alpine@SHA256:" + "a" * 64,
            "DoCkEr://alpine@sha256:" + "A" * 64,
            "docker://alpine@sha256:" + "g" * 64,
            "docker://alpine@sha384:" + "b" * 64,
            "docker://alpine@sha512:" + "c" * 64,
            "docker://alpine@md5:" + "a" * 32,
            f"docker://alpine@{DOCKER_DIGEST}@{DOCKER_DIGEST}",
            f"docker://alpine@{DOCKER_DIGEST}suffix",
            f"docKer://alpine@{DOCKER_DIGEST}",
            f"docker://alpine@{DOCKER_DIGEST}\n",
            f"docker://al pine@{DOCKER_DIGEST}",
            "docker://${{inputs.image}}@" + DOCKER_DIGEST,
            "docker://alpine@${{inputs.digest}}",
        ]
        for reference in references:
            with self.subTest(reference=reference):
                # Workflow steps, composite steps, and Docker Action metadata
                # all select executable images. Keep the other surfaces valid
                # so each rejection identifies the reference being checked.
                self.workflow("jobs:\n  build:\n    steps:\n"
                              f"      - uses: {json.dumps(reference)}\n")
                result = self.run_checker()
                self.assertEqual(result.returncode, 1, result.stderr)
                self.assertIn("check.yml: job build step 1: Docker Action needs",
                              result.stderr)
                self.workflow("jobs:\n  build:\n    steps:\n"
                              f"      - uses: owner/action@{SHA}\n")
                action = self.write(
                    ".github/actions/local/action.yml", HASH_HEADER +
                    "runs:\n  using: composite\n  steps:\n"
                    f"    - uses: {json.dumps(reference)}\n",
                )
                result = self.run_checker()
                self.assertEqual(result.returncode, 1, result.stderr)
                self.assertIn("action.yml: step 1: Docker Action needs",
                              result.stderr)
                action.unlink()
                action = self.write(
                    ".github/actions/local/action.yaml", HASH_HEADER +
                    "runs:\n  using: docker\n"
                    f"  image: {json.dumps(reference)}\n",
                )
                result = self.run_checker()
                self.assertEqual(result.returncode, 1, result.stderr)
                self.assertIn("action.yaml: runs.image: Docker Action needs",
                              result.stderr)
                action.unlink()

