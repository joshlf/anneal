//! Maintain the verifier's embedded copy of its audited source resources.
//!
//! Run this tool explicitly after changing a bundled source:
//! `cargo run -p cargo-anneal --example regenerate_bundle -- --root .`.
//! CI adds `--check` to reject stale generated bytes. Ordinary builds never
//! read the source checkout, so the extracted registry package is self-contained.

use clap::Parser;
use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::io::{self, Write as _};
use std::path::{Path, PathBuf};

// Keep resource ownership explicit: runtime discovery from a target
// checkout would let unreviewed files replace the installed model or
// inspector. Missing imports fail during fresh proof compilation; this
// inventory must grow with the canonical resources they require.
const SOURCES: &[&str] = &[
    "trusted/audit/TrustedBoundary.lean",
    "trusted/audit/library-lock.json",
    "trusted/lean/foundation-lock.json",
    "trusted/lean/lean-toolchain",
    "trusted/lean/Trusted.lean",
    "trusted/lean/Trusted/Mvp.lean",
    "trusted/lean/Trusted/Mvp/Semantics.lean",
    "trusted/lean/Trusted/Mvp/Syntax.lean",
    "theory/Anneal.lean",
    "theory/Anneal/Mvp/Canaries.lean",
    "theory/Anneal/Mvp/Execution.lean",
];

const DESTINATION: &str = "trusted/cargo-anneal/src/bundled_resources.rs";

const HEADER: &str = "\
// Copyright 2026 The Fuchsia Authors
//
// Licensed under a BSD-style license <LICENSE-BSD>, Apache License, Version 2.0
// <LICENSE-APACHE or https://www.apache.org/licenses/LICENSE-2.0>, or the MIT
// license <LICENSE-MIT or https://opensource.org/licenses/MIT>, at your option.
// This file may not be copied, modified, or distributed except according to
// those terms.

// @generated by examples/regenerate_bundle.rs; do not edit.
// Regenerate with:
// cargo run -p cargo-anneal --example regenerate_bundle -- --root .

#[rustfmt::skip]
const BUNDLE: &[(&str, &str)] = &[
";

#[derive(Parser)]
#[command(about = "Regenerate or check the verifier's embedded source resources")]
struct Args {
    /// Repository root containing the canonical sources and generated output.
    #[arg(long)]
    root: PathBuf,
    /// Compare the generated bytes without changing any file.
    #[arg(long)]
    check: bool,
}

fn render(root: &Path) -> Result<String, Box<dyn Error>> {
    let mut generated = HEADER.to_owned();
    for path in SOURCES {
        let source = fs::read_to_string(root.join(path))?;
        // Rust's standard string formatter supplies valid Rust literal escapes.
        // The embedded bytes must equal the canonical UTF-8 source exactly.
        writeln!(
            generated,
            "    (\n        {path:?},\n        {source:?},\n    ),"
        )?;
    }
    generated.push_str("];\n");
    Ok(generated)
}

fn bundle_destination(root: &Path) -> io::Result<(PathBuf, Option<fs::Permissions>)> {
    // Regeneration assumes a stable, cooperatively maintained checkout. Check
    // each fixed output parent so symlinks cannot redirect a maintenance write.
    let mut directory = root.to_path_buf();
    for component in ["trusted", "cargo-anneal", "src"] {
        directory.push(component);
        if !fs::symlink_metadata(&directory)?.is_dir() {
            return Err(io::Error::other(format!(
                "bundle parent must be a regular directory: {}",
                directory.display()
            )));
        }
    }
    let destination = root.join(DESTINATION);
    let permissions = match fs::symlink_metadata(&destination) {
        Ok(metadata) if metadata.is_file() => Some(metadata.permissions()),
        Ok(_) => {
            return Err(io::Error::other(format!(
                "bundle destination must be a regular file: {}",
                destination.display()
            )));
        }
        Err(error) if error.kind() == io::ErrorKind::NotFound => None,
        Err(error) => return Err(error),
    };
    Ok((destination, permissions))
}

fn run(args: Args) -> Result<(), Box<dyn Error>> {
    let root = fs::canonicalize(args.root)?;
    let expected = render(&root)?;
    let (destination, permissions) = bundle_destination(&root)?;
    // Build and CI callers only compare bytes. Regeneration is an explicit
    // maintenance write, so a stale package cannot silently repair itself
    // while claiming to check the audited canonical sources.
    if args.check {
        if fs::read(&destination)? != expected.as_bytes() {
            return Err(io::Error::other(format!(
                "{} differs from its canonical sources; run regenerate_bundle without --check",
                destination.display()
            ))
            .into());
        }
    } else {
        // Replacing the named file keeps every other hard link to its old
        // inode unchanged. Preserve the destination's permissions on the new
        // file before the same-directory rename makes the update visible.
        let mut temporary = tempfile::NamedTempFile::new_in(
            destination
                .parent()
                .expect("the fixed output path has a parent"),
        )?;
        temporary.write_all(expected.as_bytes())?;
        if let Some(permissions) = permissions {
            temporary.as_file().set_permissions(permissions)?;
        }
        temporary.persist(destination)?;
    }
    Ok(())
}

fn main() -> Result<(), Box<dyn Error>> {
    run(Args::parse())
}

#[cfg(all(test, unix))]
mod tests {
    use super::*;
    use std::os::unix::fs::{PermissionsExt, symlink};

    fn repository(root: &Path) {
        for source in SOURCES {
            let path = root.join(source);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(path, format!("canonical bytes for {source}\n")).unwrap();
        }
        fs::create_dir_all(root.join(DESTINATION).parent().unwrap()).unwrap();
    }

    #[test]
    fn regeneration_preserves_outside_hard_link_and_output_permissions() {
        let fixture = tempfile::tempdir().unwrap();
        let root = fixture.path().join("repository");
        repository(&root);
        let outside = fixture.path().join("outside.rs");
        let original = b"outside file must remain unchanged\n";
        fs::write(&outside, original).unwrap();
        fs::set_permissions(&outside, fs::Permissions::from_mode(0o640)).unwrap();
        let destination = root.join(DESTINATION);
        fs::hard_link(&outside, &destination).unwrap();

        run(Args {
            root: root.clone(),
            check: false,
        })
        .unwrap();

        assert_eq!(fs::read(&outside).unwrap(), original);
        assert_eq!(
            fs::read(&destination).unwrap(),
            render(&root).unwrap().as_bytes()
        );
        assert_eq!(
            fs::metadata(destination).unwrap().permissions().mode() & 0o777,
            0o640
        );
    }

    #[test]
    fn both_modes_reject_symlinked_output_without_changing_its_target() {
        let fixture = tempfile::tempdir().unwrap();
        let root = fixture.path().join("repository");
        repository(&root);
        let outside = fixture.path().join("outside.rs");
        fs::write(&outside, b"outside sentinel\n").unwrap();
        symlink(&outside, root.join(DESTINATION)).unwrap();

        for check in [false, true] {
            let error = run(Args {
                root: root.clone(),
                check,
            })
            .unwrap_err();
            assert!(error.to_string().contains("regular file"), "{error}");
            assert_eq!(fs::read(&outside).unwrap(), b"outside sentinel\n");
        }
    }

    #[test]
    fn both_modes_reject_symlinked_output_parent() {
        let fixture = tempfile::tempdir().unwrap();
        let root = fixture.path().join("repository");
        repository(&root);
        let outside = fixture.path().join("outside");
        fs::create_dir(&outside).unwrap();
        let source_directory = root.join(DESTINATION).parent().unwrap().to_owned();
        fs::remove_dir(&source_directory).unwrap();
        symlink(&outside, source_directory).unwrap();

        for check in [false, true] {
            let error = run(Args {
                root: root.clone(),
                check,
            })
            .unwrap_err();
            assert!(error.to_string().contains("regular directory"), "{error}");
            assert_eq!(fs::read_dir(&outside).unwrap().count(), 0);
        }
    }
}
